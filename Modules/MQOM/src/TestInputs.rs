/// The bytes of the seeded sequence of the C program: each byte is bits 16 to 23 of the next
/// state.
pub(crate) fn sequenceBytes(count: usize, seed: u32) -> Vec<u8> {
    let mut sequence = LinearCongruentialSequence::new(seed);
    (0..count)
        .map(|_| (sequence.nextState() >> 16) as u8)
        .collect()
}

/// Elements of the extension field of a set, read from the bytes of a sequence as
/// `field_ext_parse` reads them.
pub(crate) fn sequenceElements(parameters: &Parameters, count: usize, seed: u32) -> Vec<u16> {
    let field = parameters.extensionField;
    field.decoded(&sequenceBytes(count * field.byteCount(), seed))
}

/// Rows of elements of the extension field, read one after another from one sequence, as the C
/// program fills a two-dimensional array.
pub(crate) fn sequenceRows(
    parameters: &Parameters,
    rowCount: usize,
    columnCount: usize,
    seed: u32,
) -> Vec<Vec<u16>> {
    sequenceElements(parameters, rowCount * columnCount, seed)
        .chunks_exact(columnCount)
        .map(<[u16]>::to_vec)
        .collect()
}

/// A hidden leaf for each repetition: the little-endian 16-bit values of a sequence, cut to the
/// tree depth.
pub(crate) fn sequenceHiddenLeaves(parameters: &Parameters, seed: u32) -> Vec<u16> {
    sequenceBytes(2 * parameters.repetitionCount, seed)
        .chunks_exact(2)
        .map(|pair| u16::from_le_bytes([pair[0], pair[1]]) & (parameters.leafCount() as u16 - 1))
        .collect()
}

/// The digest of elements of the extension field, serialized as the C program serializes them.
pub(crate) fn elementsDigest(parameters: &Parameters, rows: &[Vec<u16>]) -> String {
    let bytes: Vec<u8> = rows
        .iter()
        .flat_map(|row| parameters.extensionField.encoded(row))
        .collect();
    OutputDigest::of(&bytes)
}

