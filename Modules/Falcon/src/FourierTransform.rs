use crate::floatingPoint::FloatingPoint;

/// The fast Fourier transform of Falcon over polynomials modulo `X^N + 1`, and the operations
/// on polynomials in its representation, as `fft.c` of the Falcon code of PQClean gives them.
///
/// A polynomial of `N = 2^logn` real coefficients becomes `N / 2` complex values, the values
/// at the roots `w_j = exp(i pi (2 j + 1) / N)` for `j < N / 2`. The value at `w_j` keeps its
/// real part in slot `rev(j) / 2` and its imaginary part in slot `rev(j) / 2 + N / 2`, where
/// `rev` reverses the bits of `j`. The other half of the values are the conjugates, which are
/// not stored. Each function makes the operations of the C code in the same order, so the
/// results are the same bits.
pub(crate) struct FourierTransform;

/// The product of two complex values, as the `FPC_MUL` macro computes it.
fn complexProduct(
    leftReal: FloatingPoint,
    leftImaginary: FloatingPoint,
    rightReal: FloatingPoint,
    rightImaginary: FloatingPoint,
) -> (FloatingPoint, FloatingPoint) {
    (
        leftReal * rightReal - leftImaginary * rightImaginary,
        leftReal * rightImaginary + leftImaginary * rightReal,
    )
}

/// The quotient of two complex values, as the `FPC_DIV` macro computes it.
fn complexQuotient(
    leftReal: FloatingPoint,
    leftImaginary: FloatingPoint,
    rightReal: FloatingPoint,
    rightImaginary: FloatingPoint,
) -> (FloatingPoint, FloatingPoint) {
    let scale = (rightReal.squared() + rightImaginary.squared()).inverse();
    let rightReal = rightReal * scale;
    let rightImaginary = -rightImaginary * scale;
    complexProduct(leftReal, leftImaginary, rightReal, rightImaginary)
}

impl FourierTransform {
    /// The root `GM[k] = w^rev(k)` of the transform, for the primitive 2048th root of unity
    /// `w = exp(i pi / 1024)` and the 10-bit reversal `rev`: its real and imaginary parts.
    fn root(index: usize) -> (FloatingPoint, FloatingPoint) {
        (
            FloatingPoint::fromBits(rootTable[2 * index]),
            FloatingPoint::fromBits(rootTable[2 * index + 1]),
        )
    }

    /// The transform in place, as `FFT` does: the `N` coefficients of a real polynomial become
    /// its `N / 2` complex values.
    pub(crate) fn transform(values: &mut [FloatingPoint], logn: u32) {
        // The first step multiplies by GM[1] = i, which the representation already is.
        let n = 1usize << logn;
        let hn = n >> 1;
        let mut t = hn;
        let mut m = 2;
        for _ in 1..logn {
            let ht = t >> 1;
            let hm = m >> 1;
            for i1 in 0..hm {
                let j1 = i1 * t;
                let (sReal, sImaginary) = Self::root(m + i1);
                for j in j1..j1 + ht {
                    let (xReal, xImaginary) = (values[j], values[j + hn]);
                    let (yReal, yImaginary) =
                        complexProduct(values[j + ht], values[j + ht + hn], sReal, sImaginary);
                    values[j] = xReal + yReal;
                    values[j + hn] = xImaginary + yImaginary;
                    values[j + ht] = xReal - yReal;
                    values[j + ht + hn] = xImaginary - yImaginary;
                }
            }
            t = ht;
            m <<= 1;
        }
    }

    /// The inverse transform in place, as `iFFT` does. The last step of the algorithm is a
    /// doubling, which the final division by `N / 2` instead of `N` makes.
    pub(crate) fn inverseTransform(values: &mut [FloatingPoint], logn: u32) {
        let n = 1usize << logn;
        let hn = n >> 1;
        let mut t = 1;
        let mut m = n;
        for _ in (2..=logn).rev() {
            let hm = m >> 1;
            let dt = t << 1;
            for (i1, j1) in (0..hn).step_by(dt).enumerate() {
                let (sReal, sImaginary) = Self::root(hm + i1);
                let sImaginary = -sImaginary;
                for j in j1..j1 + t {
                    let (xReal, xImaginary) = (values[j], values[j + hn]);
                    let (yReal, yImaginary) = (values[j + t], values[j + t + hn]);
                    values[j] = xReal + yReal;
                    values[j + hn] = xImaginary + yImaginary;
                    let (product, productImaginary) =
                        complexProduct(xReal - yReal, xImaginary - yImaginary, sReal, sImaginary);
                    values[j + t] = product;
                    values[j + t + hn] = productImaginary;
                }
            }
            t = dt;
            m = hm;
        }
        if logn > 0 {
            let scale = FloatingPoint::fromBits(inverseHalfDegrees[logn as usize]);
            for value in values[..n].iter_mut() {
                *value = *value * scale;
            }
        }
    }

    /// Adds a polynomial to another, as `poly_add` does, in either representation.
    pub(crate) fn add(values: &mut [FloatingPoint], other: &[FloatingPoint], logn: u32) {
        for (value, addend) in values[..1 << logn].iter_mut().zip(other) {
            *value = *value + *addend;
        }
    }

    /// Subtracts a polynomial from another, as `poly_sub` does, in either representation.
    pub(crate) fn subtract(values: &mut [FloatingPoint], other: &[FloatingPoint], logn: u32) {
        for (value, subtrahend) in values[..1 << logn].iter_mut().zip(other) {
            *value = *value - *subtrahend;
        }
    }

    /// Negates a polynomial, as `poly_neg` does, in either representation.
    pub(crate) fn negate(values: &mut [FloatingPoint], logn: u32) {
        for value in values[..1 << logn].iter_mut() {
            *value = -*value;
        }
    }

    /// Replaces a polynomial with its adjoint, as `poly_adj_fft` does.
    pub(crate) fn adjoint(values: &mut [FloatingPoint], logn: u32) {
        let n = 1usize << logn;
        for value in values[n >> 1..n].iter_mut() {
            *value = -*value;
        }
    }

    /// Multiplies a polynomial by another, as `poly_mul_fft` does.
    pub(crate) fn multiply(values: &mut [FloatingPoint], other: &[FloatingPoint], logn: u32) {
        let hn = (1usize << logn) >> 1;
        for u in 0..hn {
            let (real, imaginary) =
                complexProduct(values[u], values[u + hn], other[u], other[u + hn]);
            values[u] = real;
            values[u + hn] = imaginary;
        }
    }

    /// Multiplies a polynomial by the adjoint of another, as `poly_muladj_fft` does.
    pub(crate) fn multiplyByAdjoint(
        values: &mut [FloatingPoint],
        other: &[FloatingPoint],
        logn: u32,
    ) {
        let hn = (1usize << logn) >> 1;
        for u in 0..hn {
            let (real, imaginary) =
                complexProduct(values[u], values[u + hn], other[u], -other[u + hn]);
            values[u] = real;
            values[u + hn] = imaginary;
        }
    }

    /// Multiplies a polynomial by its own adjoint, which gives real values, as
    /// `poly_mulselfadj_fft` does.
    pub(crate) fn multiplyBySelfAdjoint(values: &mut [FloatingPoint], logn: u32) {
        let hn = (1usize << logn) >> 1;
        for u in 0..hn {
            values[u] = values[u].squared() + values[u + hn].squared();
            values[u + hn] = FloatingPoint::zero;
        }
    }

    /// Multiplies a polynomial by a constant, as `poly_mulconst` does, in either
    /// representation.
    pub(crate) fn multiplyByConstant(
        values: &mut [FloatingPoint],
        constant: FloatingPoint,
        logn: u32,
    ) {
        for value in values[..1 << logn].iter_mut() {
            *value = *value * constant;
        }
    }

    /// The real values `1 / (a adj(a) + b adj(b))` of two polynomials, as
    /// `poly_invnorm2_fft` does. Only the first `N / 2` slots of the result are written.
    pub(crate) fn inverseNorm(
        result: &mut [FloatingPoint],
        a: &[FloatingPoint],
        b: &[FloatingPoint],
        logn: u32,
    ) {
        let hn = (1usize << logn) >> 1;
        for u in 0..hn {
            let aNorm = a[u].squared() + a[u + hn].squared();
            let bNorm = b[u].squared() + b[u + hn].squared();
            result[u] = (aNorm + bNorm).inverse();
        }
    }

    /// The polynomial `F adj(f) + G adj(g)`, as `poly_add_muladj_fft` does.
    pub(crate) fn sumOfAdjointProducts(
        result: &mut [FloatingPoint],
        bigF: &[FloatingPoint],
        bigG: &[FloatingPoint],
        f: &[FloatingPoint],
        g: &[FloatingPoint],
        logn: u32,
    ) {
        let hn = (1usize << logn) >> 1;
        for u in 0..hn {
            let (aReal, aImaginary) = complexProduct(bigF[u], bigF[u + hn], f[u], -f[u + hn]);
            let (bReal, bImaginary) = complexProduct(bigG[u], bigG[u + hn], g[u], -g[u + hn]);
            result[u] = aReal + bReal;
            result[u + hn] = aImaginary + bImaginary;
        }
    }

    /// Multiplies a polynomial by an auto-adjoint polynomial, whose `N / 2` values are real,
    /// as `poly_mul_autoadj_fft` does.
    pub(crate) fn multiplyByAutoAdjoint(
        values: &mut [FloatingPoint],
        other: &[FloatingPoint],
        logn: u32,
    ) {
        let hn = (1usize << logn) >> 1;
        for u in 0..hn {
            values[u] = values[u] * other[u];
            values[u + hn] = values[u + hn] * other[u];
        }
    }

    /// Divides a polynomial by an auto-adjoint polynomial, whose `N / 2` values are real, as
    /// `poly_div_autoadj_fft` does.
    pub(crate) fn divideByAutoAdjoint(
        values: &mut [FloatingPoint],
        other: &[FloatingPoint],
        logn: u32,
    ) {
        let hn = (1usize << logn) >> 1;
        for u in 0..hn {
            let inverse = other[u].inverse();
            values[u] = values[u] * inverse;
            values[u + hn] = values[u + hn] * inverse;
        }
    }

    /// The LDL decomposition of the auto-adjoint matrix `[[g00, g01], [adj(g01), g11]]` in
    /// place, as `poly_LDL_fft` does: `g01` becomes `l10` and `g11` becomes `d11`, and `g00`
    /// is `d00`.
    pub(crate) fn decomposeLDL(
        g00: &[FloatingPoint],
        g01: &mut [FloatingPoint],
        g11: &mut [FloatingPoint],
        logn: u32,
    ) {
        let hn = (1usize << logn) >> 1;
        for u in 0..hn {
            let (g01Real, g01Imaginary) = (g01[u], g01[u + hn]);
            let (muReal, muImaginary) = complexQuotient(g01Real, g01Imaginary, g00[u], g00[u + hn]);
            let (productReal, productImaginary) =
                complexProduct(muReal, muImaginary, g01Real, -g01Imaginary);
            g11[u] = g11[u] - productReal;
            g11[u + hn] = g11[u + hn] - productImaginary;
            g01[u] = muReal;
            g01[u + hn] = -muImaginary;
        }
    }

    /// Splits a polynomial `f = f0(X^2) + X f1(X^2)` into the halves `f0` and `f1` of half the
    /// degree, as `poly_split_fft` does. Each half has `N / 2` slots.
    pub(crate) fn split(
        f0: &mut [FloatingPoint],
        f1: &mut [FloatingPoint],
        f: &[FloatingPoint],
        logn: u32,
    ) {
        let hn = (1usize << logn) >> 1;
        let qn = hn >> 1;
        // For logn = 1 the loop is empty and these copies are the result.
        f0[0] = f[0];
        f1[0] = f[hn];
        for u in 0..qn {
            let (aReal, aImaginary) = (f[2 * u], f[2 * u + hn]);
            let (bReal, bImaginary) = (f[2 * u + 1], f[2 * u + 1 + hn]);
            f0[u] = (aReal + bReal).halved();
            f0[u + qn] = (aImaginary + bImaginary).halved();
            let (rootReal, rootImaginary) = Self::root(u + hn);
            let (real, imaginary) = complexProduct(
                aReal - bReal,
                aImaginary - bImaginary,
                rootReal,
                -rootImaginary,
            );
            f1[u] = real.halved();
            f1[u + qn] = imaginary.halved();
        }
    }

    /// Merges two halves `f0` and `f1` into `f = f0(X^2) + X f1(X^2)`, as `poly_merge_fft`
    /// does.
    pub(crate) fn merge(
        f: &mut [FloatingPoint],
        f0: &[FloatingPoint],
        f1: &[FloatingPoint],
        logn: u32,
    ) {
        let hn = (1usize << logn) >> 1;
        let qn = hn >> 1;
        // For logn = 1 the loop is empty and these copies are the result.
        f[0] = f0[0];
        f[hn] = f1[0];
        for u in 0..qn {
            let (aReal, aImaginary) = (f0[u], f0[u + qn]);
            let (rootReal, rootImaginary) = Self::root(u + hn);
            let (bReal, bImaginary) = complexProduct(f1[u], f1[u + qn], rootReal, rootImaginary);
            f[2 * u] = aReal + bReal;
            f[2 * u + hn] = aImaginary + bImaginary;
            f[2 * u + 1] = aReal - bReal;
            f[2 * u + 1 + hn] = aImaginary - bImaginary;
        }
    }
}

