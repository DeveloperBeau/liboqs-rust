    #[test]
    fn productInTheTransformIsTheNegacyclicProduct() {
        // The product modulo X^N + 1 by the schoolbook method is the independent answer.
        for logn in [1u32, 3, 6, 9, 10] {
            let n = 1usize << logn;
            let left: Vec<i64> = (0..n).map(|u| ((u * 37 + 11) % 101) as i64 - 50).collect();
            let right: Vec<i64> = (0..n).map(|u| ((u * 53 + 7) % 89) as i64 - 44).collect();
            let mut expected = vec![0i64; n];
            for (i, a) in left.iter().enumerate() {
                for (j, b) in right.iter().enumerate() {
                    let sign = if i + j < n { 1 } else { -1 };
                    expected[(i + j) % n] += sign * a * b;
                }
            }
            let toValues = |integers: &[i64]| -> Vec<FloatingPoint> {
                integers
                    .iter()
                    .map(|value| FloatingPoint::of(*value))
                    .collect()
            };
            let mut product = transformed(toValues(&left), logn);
            FourierTransform::multiply(&mut product, &transformed(toValues(&right), logn), logn);
            FourierTransform::inverseTransform(&mut product, logn);
            let rounded: Vec<i64> = product
                .iter()
                .map(|value| value.roundedToNearest())
                .collect();
            assert_eq!(rounded, expected, "logn {logn}");
        }
    }

    #[test]
    fn splitAndMergeAreInverseOperations() {
        for logn in [1u32, 2, 5, 10] {
            let n = 1usize << logn;
            let f = transformed(loaded(logn, 37, 11, 101), logn);
            let mut halves = vec![FloatingPoint::zero; n];
            let (f0, f1) = halves.split_at_mut(n / 2);
            FourierTransform::split(f0, f1, &f, logn);
            let mut merged = vec![FloatingPoint::zero; n];
            FourierTransform::merge(&mut merged, &halves[..n / 2], &halves[n / 2..], logn);
            for (u, (value, original)) in merged.iter().zip(&f).enumerate() {
                let difference = f64::from_bits((*value - *original).bits()).abs();
                assert!(difference < 1e-9, "logn {logn}, slot {u}");
            }
        }
    }
